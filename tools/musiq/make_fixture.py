#!/usr/bin/env python3
"""Write internal/ml/testdata/musiq_ref.json: what the PyTorch port computes
for a few synthetic images, for the Go tests (internal/ml/musiq_test.go).

    make_fixture.py KONIQ_CKPT.npz OUT.json

Each image is generated from a formula both sides share (no decoding): pixel
(x, y, channel c) = (7x + 13y + 50c + (x*y mod 31)) mod 256. For each it
records the sequence's per-scale sums, sampled token values and the score.
"""
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import preprocess as pp  # noqa: E402
from export_onnx import MAX_TOKENS  # noqa: E402
from model import MUSIQ  # noqa: E402

SIZES = [(400, 300), (257, 512), (512, 512), (90, 61)]  # (w, h)


def image(w, h):
    y, x, c = np.meshgrid(np.arange(h), np.arange(w), np.arange(3), indexing="ij")
    return ((7 * x + 13 * y + 50 * c + (x * y) % 31) % 256).astype(np.uint8)


def main():
    m = MUSIQ(sys.argv[1])
    rng = np.random.default_rng(1)
    cases = []
    for w, h in SIZES:
        seq = pp.multiscale(pp.from_uint8(image(w, h)))
        full = np.concatenate([seq, np.zeros((MAX_TOKENS - len(seq), seq.shape[1]), np.float32)])
        idx = sorted(rng.choice(full.size, 64, replace=False).tolist())
        # make sure some samples land on real pixels of every scale
        for t in (0, 49, 49 + 144, len(seq) - 1):
            idx += [t * full.shape[1] + k for k in (0, 100, 3071, 3072, 3073, 3074)]
        idx = sorted(set(idx))
        cases.append({
            "w": w, "h": h, "tokens": int(len(seq)),
            "sum": float(full.astype(np.float64).sum()),
            "abs_sum": float(np.abs(full.astype(np.float64)).sum()),
            "samples": [[i, float(full.flat[i])] for i in idx],
            "score": m.score(seq),
        })
        print(w, h, len(seq), cases[-1]["score"])
    with open(sys.argv[2], "w") as f:
        json.dump({"note": "generated by tools/musiq/make_fixture.py", "cases": cases}, f, indent=1)


if __name__ == "__main__":
    main()
